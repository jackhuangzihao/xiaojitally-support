#!/usr/bin/env python3
"""Open copies of the frozen synthetic build-52 and build-68 stores with a new app executable.

Usage: python3 Checks/check_migration.py /path/to/小记.app/Contents/MacOS/Jianshi
Committed fixtures are never opened by SwiftData or regenerated by this check.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


def check_fixture(executable, build):
    fixture = Path(__file__).resolve().parent / f"Fixtures/schema-{build}"
    manifest = json.loads((fixture / "manifest.json").read_text())
    if manifest.get("synthetic") is not True or manifest.get("sourceBuild") != f"1.0 ({build})":
        raise SystemExit("Only the matching frozen synthetic fixture is allowed")
    expected_files = {"store.sqlite", "expected.json", "cloud-baseline.json", "cloud-state.json"}
    if set(manifest["filesSHA256"]) != expected_files:
        raise SystemExit("Unexpected fixture manifest contents")
    for name, expected in manifest["filesSHA256"].items():
        actual = hashlib.sha256((fixture / name).read_bytes()).hexdigest()
        if actual != expected:
            raise SystemExit(f"Frozen fixture changed: schema-{build}/{name}")
    if build == 52:
        expected = json.loads((fixture / "expected.json").read_text())
        if expected["version"] != 6 or "weekTitles" in expected:
            raise SystemExit("Build-52 fixture lost its original version or absent week titles")
    print(f"FROZEN MIGRATION CHECK: pinned build-{build} synthetic store", flush=True)
    with tempfile.TemporaryDirectory(prefix=f"tally-migration-check-{build}-") as folder:
        copy = Path(folder) / "previous.store"
        shutil.copyfile(fixture / "store.sqlite", copy)
        env = {k: v for k, v in os.environ.items()
               if not k.startswith(("JIANSHI_", "SIMCTL_CHILD_JIANSHI_"))}
        env.update({
            "JIANSHI_MIGRATION_COPY": str(copy),
            "JIANSHI_MIGRATION_EXPECTED": str(fixture / "expected.json"),
            "JIANSHI_MIGRATION_CLOUD_BASELINE": str(fixture / "cloud-baseline.json"),
            "JIANSHI_MIGRATION_CLOUD_STATE": str(fixture / "cloud-state.json"),
        })
        subprocess.run([str(executable), "--self-check"], env=env, check=True)
    print(f"Frozen build-{build} migration passed", flush=True)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    executable = Path(sys.argv[1]).resolve()
    if not executable.is_file():
        raise SystemExit("App executable does not exist")
    for build in (52, 68):
        check_fixture(executable, build)
    print("FROZEN MIGRATION PASS: pinned build-52 and build-68 synthetic stores")


if __name__ == "__main__":
    main()
